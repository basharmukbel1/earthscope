/** Assert |actual − expected| ≤ max(abs, rel·|expected|). */
export function close(actual: number, expected: number, rel = 1e-9, abs = 0, label = ""): void {
  if (!Number.isFinite(expected)) {
    expect(actual, label).toBe(expected);
    return;
  }
  const tol = Math.max(abs, rel * Math.abs(expected));
  const diff = Math.abs(actual - expected);
  expect(
    diff,
    `${label} actual=${actual} expected=${expected} |Δ|=${diff.toExponential(3)} tol=${tol.toExponential(3)}`,
  ).toBeLessThanOrEqual(tol);
}

/** Build monthly Points from parallel t/date/value arrays. */
export function toPoints(t: number[], v: N[], dates?: string[]): Point[] {
  return t.map((ti, i) => ({ t: ti, date: dates ? dates[i] : String(ti), v: v[i] }));
}
