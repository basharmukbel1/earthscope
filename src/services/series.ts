/* ==========================================================================
   Builds regional monthly time series for catalog variables.
   power   → area-weighted mean over the sampling plan (live NASA POWER)
   bundled → real snapshot JSON shipped with the app (src/data/external)
   Fallback: if POWER is unreachable, a bundled real snapshot of the same
   request (public/snapshots, generated by scripts/build-snapshots.ts) is used
   and clearly labelled as such.
   ========================================================================== */

export interface FetchProgress {
  done: number;
  total: number;
  phase: "plan" | "fetch" | "aggregate" | "snapshot";
  message: string;
}

export interface RegionSeriesResult {
  series: TimeSeries[];
  plan: SamplePlan | null;
  usedSnapshot: boolean;
  warnings: string[];
}

export async function loadSnapshot(id: string): Promise<TimeSeries[] | null> {
  try {
    const res = await fetch(`/snapshots/${encodeURIComponent(id)}.json`);
    if (!res.ok) return null;
    const data = (await res.json()) as TimeSeries[];
    return Array.isArray(data) ? data : null;
  } catch {
    return null;
  }
}

/* --------------------------------------------------------------------------
   Result cache: every completed regional request is kept in memory and in
   localStorage (small: one aggregated series per variable), so going back and
   forth — or reloading — is instant. Raw POWER point responses are cached
   separately in IndexedDB (services/cache.ts). Storage errors are ignored.
   -------------------------------------------------------------------------- */
const memCache = new Map<string, RegionSeriesResult>();
const LS_PREFIX = "earthscope:series:v1:";
const LS_INDEX = "earthscope:series:v1:index";
const LS_MAX = 24;
const cacheKey = (regionId: string, ids: string[], start: number, end: number) => `${regionId}|${[...ids].sort().join(",")}|${start}-${end}`;

function lsRead(key: string): RegionSeriesResult | null {
  try {
    const raw = localStorage.getItem(LS_PREFIX + key);
    return raw ? (JSON.parse(raw) as RegionSeriesResult) : null;
  } catch {
    return null;
  }
}

function lsWrite(key: string, value: RegionSeriesResult) {
  try {
    const index = (JSON.parse(localStorage.getItem(LS_INDEX) ?? "[]") as string[]).filter((k) => k !== key);
    index.unshift(key);
    while (index.length > LS_MAX) localStorage.removeItem(LS_PREFIX + index.pop());
    const payload = JSON.stringify(value);
    for (let attempt = 0; attempt < 3; attempt++) {
      try {
        localStorage.setItem(LS_PREFIX + key, payload);
        break;
      } catch {
        // Storage full: drop the oldest half and try again.
        for (const k of index.splice(Math.max(1, Math.ceil(index.length / 2)))) localStorage.removeItem(LS_PREFIX + k);
      }
    }
    localStorage.setItem(LS_INDEX, JSON.stringify(index));
  } catch {
    /* storage unavailable (private mode, disabled) — memory cache still works */
  }
}

/** Real bundled external datasets (NSIDC sea ice, MODIS NDVI points …). */
const externalModules = import.meta.glob<{ default: TimeSeries }>("../data/external/*.json");

export async function loadBundledSeries(snapshotId: string): Promise<TimeSeries | null> {
  const entry = Object.entries(externalModules).find(([path]) => path.endsWith(`/${snapshotId}.json`));
  if (!entry) return null;
  try {
    const mod = await entry[1]();
    return mod.default;
  } catch {
    return null;
  }
}

export async function listBundledSeries(): Promise<string[]> {
  return Object.keys(externalModules)
    .map((p) => p.split("/").pop()!.replace(/\.json$/, ""))
    .filter((id) => id !== "manifest");
}

/**
 * Fetch monthly regional series for the given POWER-backed variables.
 * One POWER request per sample point returns all variables at once.
 */
export async function fetchRegionSeries(
  region: Region,
  variableIds: string[],
  start: number,
  end: number,
  opts: { signal?: AbortSignal; onProgress?: (p: FetchProgress) => void; allowSnapshot?: boolean } = {},
): Promise<RegionSeriesResult> {
  const vars = variableIds.map((id) => getVariable(id)).filter((v): v is Variable => !!v);
  const powerVars = vars.filter((v) => v.connector.kind === "power");
  const warnings: string[] = [];
  const series: TimeSeries[] = [];

  // Bundled (non-POWER) variables: only meaningful when a snapshot exists.
  for (const v of vars.filter((x) => x.connector.kind !== "power")) {
    warnings.push(
      `${v.name} is not available from NASA POWER. Load a bundled snapshot or import a CSV from ${
        v.connector.kind === "import" || v.connector.kind === "bundled" ? v.connector.tools.join(" / ") : "Giovanni"
      }.`,
    );
  }
  if (powerVars.length === 0) return { series, plan: null, usedSnapshot: false, warnings };

  const key = cacheKey(region.id, powerVars.map((v) => v.id), start, end);
  const cached = memCache.get(key) ?? lsRead(key);
  if (cached) {
    memCache.set(key, cached);
    const n = cached.plan?.points.length ?? 1;
    opts.onProgress?.({ done: n, total: n, phase: "fetch", message: "Loaded from this device — no new download needed" });
    return { ...cached, warnings: [...warnings, ...cached.warnings] };
  }

  opts.onProgress?.({ done: 0, total: 1, phase: "plan", message: "Building spatial sampling plan…" });
  const feature = await countryFeatureFor(region);
  const plan = buildSamplePlan(region, feature);

  // Effective start year per variable (e.g. AOD from 2001).
  const fetchStart = Math.min(...powerVars.map((v) => Math.max(start, (v.connector as { startYear: number }).startYear)));
  const params = powerVars.map((v) => (v.connector as { parameter: string }).parameter);

  let done = 0;
  const total = plan.points.length;
  opts.onProgress?.({ done, total, phase: "fetch", message: `Requesting ${total} grid cell${total > 1 ? "s" : ""} from NASA POWER…` });

  let results: { w: number; data: PowerPointData }[];
  try {
    results = await Promise.all(
      plan.points.map(async (pt) => {
        const data = await fetchPowerPoint({ lat: pt.lat, lon: pt.lon, parameters: params, start: fetchStart, end, signal: opts.signal });
        done++;
        opts.onProgress?.({ done, total, phase: "fetch", message: `Received ${done} of ${total} grid cells` });
        return { w: pt.w, data };
      }),
    );
  } catch (err) {
    if ((err as Error).name === "AbortError") throw err;
    if (opts.allowSnapshot === false) throw err;
    opts.onProgress?.({ done: 0, total: 1, phase: "snapshot", message: "NASA POWER unreachable — looking for a bundled snapshot…" });
    const snaps = await Promise.all(powerVars.map((v) => loadSnapshot(seriesId(region.id, v.id, start, end))));
    const found = snaps.flat().filter((s): s is TimeSeries => !!s);
    if (found.length === powerVars.length) {
      return {
        series: found,
        plan,
        usedSnapshot: true,
        warnings: [...warnings, `NASA POWER could not be reached (${(err as Error).message}). Showing a bundled real-data snapshot instead.`],
      };
    }
    throw err;
  }

  opts.onProgress?.({ done: total, total, phase: "aggregate", message: "Computing area-weighted regional means…" });
  const retrieved = new Date().toISOString();
  for (const v of powerVars) {
    const p = (v.connector as { parameter: string; startYear: number }).parameter;
    const vStart = Math.max(start, (v.connector as { startYear: number }).startYear);
    const points = aggregatePoints(
      results.map((r) => ({ w: r.w, values: r.data[p] ?? {} })),
      vStart,
      end,
    );
    const notes = [...(v.caveats ?? [])];
    if (vStart > start) notes.push(`${v.shortName} is available from ${vStart}; the series starts there.`);
    series.push({
      id: seriesId(region.id, v.id, start, end),
      variableId: v.id,
      regionId: region.id,
      label: `${v.name} · ${region.name}`,
      unit: v.unit,
      resolution: "monthly",
      points,
      provenance: {
        source: `NASA POWER API — ${v.dataset.product}`,
        mode: "live",
        retrieved,
        url: `${POWER_BASE}?parameters=${p}&community=AG&start=${vStart}&end=${end}&format=JSON`,
        sampling: plan.description,
        cellsUsed: plan.points.length,
        cellsTotal: plan.cellsTotal,
        notes,
      },
    });
  }
  const result = { series, plan, usedSnapshot: false, warnings: [] as string[] };
  memCache.set(key, result);
  lsWrite(key, result);
  return { ...result, warnings };
}
